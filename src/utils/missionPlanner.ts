// Pure math + code-generation helpers for the Mission Planner tool.
// Coordinate convention (matches HYPERLIBwro / OdomIni(x, y, theta)):
//   - Origin (0,0) = bottom-left of field, X increases right, Y increases up (mm)
//   - Heading 0deg = facing +Y ("up"); positive angle = clockwise
//   - Bearing to a point: atan2(dx, dy) in degrees, where dx = targetX - fromX, dy = targetY - fromY
//     (this matches Hyperlib_v1_6.py's `target_theta = degrees(atan2(dx, dy))`)

export interface Point {
  x: number;
  y: number;
}

export interface Pose extends Point {
  theta: number;
}

export interface MissionStep {
  index: number;
  waypoint: Point;
  distance: number;
  turnAngle: number;
  headingAfter: number;
}

/** ThetaErr-equivalent: wrap an angle to the signed range [-180, 180]. */
export function wrapAngle(angle: number): number {
  return ((angle + 180) % 360 + 360) % 360 - 180;
}

/** Pythagorean distance between two points, in mm. */
export function distanceBetween(p1: Point, p2: Point): number {
  return Math.hypot(p2.x - p1.x, p2.y - p1.y);
}

/** Bearing from `from` to `to`, in degrees [0, 360), using Hyperlib's atan2(dx, dy) convention. */
export function bearingTo(from: Point, to: Point): number {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  let deg = Math.atan2(dx, dy) * (180 / Math.PI);
  if (deg < 0) deg += 360;
  return deg;
}

/**
 * Walk through waypoints sequentially from the start pose, computing the
 * distance and turn-in-place angle needed for each leg of the mission.
 */
export function computeSteps(start: Pose, waypoints: Point[]): MissionStep[] {
  const steps: MissionStep[] = [];
  let current: Point = { x: start.x, y: start.y };
  let currentHeading = start.theta;

  waypoints.forEach((wp, i) => {
    const distance = distanceBetween(current, wp);
    const bearing = bearingTo(current, wp);
    const turnAngle = wrapAngle(bearing - currentHeading);

    steps.push({
      index: i + 1,
      waypoint: wp,
      distance,
      turnAngle,
      headingAfter: bearing,
    });

    current = wp;
    currentHeading = bearing;
  });

  return steps;
}

function fmt(n: number): string {
  return (Math.round(n * 10) / 10).toString();
}

export interface CodeBlock {
  id: string;
  title: string;
  titleAr: string;
  code: string;
}

const FILE_HEADER = `from Hyperlib_v1_6 import*
import Hyperlib_v1_6 as lib`;

// pybricks.tools: wait(), multitask(), run_task() - async helpers used by Hyperlib
// see https://docs.pybricks.com/en/latest/tools.html
const ODOMETRY_TASK = `async def odometry_task():
    while True:
        await OdomUpdate()
        await wait(LoopTime)`;

const MAIN_RUNNER = `async def main():
    await multitask(my_mission(), odometry_task())

run_task(main())`;

/**
 * Generates a step-by-step mission as labeled code blocks: turn to face each
 * waypoint, then drive straight to it while holding that heading
 * (TurnGyro + MoveGyro pairs).
 */
export function generateStepByStepBlocks(start: Pose, steps: MissionStep[]): CodeBlock[] {
  const stepLines: string[] = [];
  if (steps.length === 0) {
    stepLines.push('    # Add waypoints on the field to generate movement steps');
  } else {
    steps.forEach((step) => {
      stepLines.push(`    # Step ${step.index}: turn ${fmt(step.turnAngle)} deg, then drive ${fmt(step.distance)} mm to (${fmt(step.waypoint.x)}, ${fmt(step.waypoint.y)})`);
      stepLines.push(`    await TurnGyro(${fmt(step.headingAfter)})`);
      stepLines.push(`    await MoveGyro(${fmt(step.distance)}, ${fmt(step.headingAfter)})`);
    });
  }

  return [
    { id: 'imports', title: 'Imports', titleAr: 'الاستيراد', code: FILE_HEADER },
    {
      id: 'setup',
      title: 'Mission Setup (Odometry Init)',
      titleAr: 'إعداد المهمة (تهيئة الأودومتري)',
      code: [
        'async def my_mission():',
        '    """Auto-generated by Robotrick Mission Planner"""',
        `    await OdomIni(${fmt(start.x)}, ${fmt(start.y)}, ${fmt(start.theta)})`,
      ].join('\n'),
    },
    { id: 'steps', title: 'Mission Steps', titleAr: 'خطوات المهمة', code: stepLines.join('\n') },
    { id: 'run', title: 'Odometry Task & Run', titleAr: 'مهمة الأودومتري والتشغيل', code: [ODOMETRY_TASK, '', MAIN_RUNNER].join('\n') },
  ];
}

/**
 * Generates a Pure Pursuit mission as labeled code blocks: sets lib.PArray to
 * the waypoint list and calls PurePursuit() once to follow the whole path.
 */
export function generatePurePursuitBlocks(start: Pose, waypoints: Point[]): CodeBlock[] {
  const allPoints = [{ x: start.x, y: start.y }, ...waypoints];
  const arrayStr = allPoints.map((p) => `[${fmt(p.x)}, ${fmt(p.y)}]`).join(', ');

  const pathLines = [`    lib.PArray = [${arrayStr}]`];
  if (waypoints.length === 0) {
    pathLines.push('    # Add waypoints on the field to build the path');
  } else {
    pathLines.push('    await PurePursuit()');
  }

  return [
    { id: 'imports', title: 'Imports', titleAr: 'الاستيراد', code: FILE_HEADER },
    {
      id: 'setup',
      title: 'Mission Setup (Odometry Init)',
      titleAr: 'إعداد المهمة (تهيئة الأودومتري)',
      code: [
        'async def my_mission():',
        '    """Auto-generated by Robotrick Mission Planner"""',
        `    await OdomIni(${fmt(start.x)}, ${fmt(start.y)}, ${fmt(start.theta)})`,
      ].join('\n'),
    },
    { id: 'path', title: 'Path & Pure Pursuit', titleAr: 'المسار وبيور برسوت', code: pathLines.join('\n') },
    { id: 'run', title: 'Odometry Task & Run', titleAr: 'مهمة الأودومتري والتشغيل', code: [ODOMETRY_TASK, '', MAIN_RUNNER].join('\n') },
  ];
}

/** Joins labeled code blocks into a single downloadable .py file. */
export function blocksToFile(blocks: CodeBlock[]): string {
  return blocks.map((b) => b.code).join('\n\n');
}
